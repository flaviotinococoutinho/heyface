export type Message = keyof typeof pt;
export function useLocale() {
  const [locale, setLocale] = useState<"pt-BR" | "en">(() =>
    localStorage.getItem("heyface.locale") === "en" ? "en" : "pt-BR",
  );
  useEffect(() => {
    document.documentElement.lang = locale;
    localStorage.setItem("heyface.locale", locale);
  }, [locale]);
  return {
    locale,
    setLocale,
    t: (key: Message) => (locale === "en" ? en : pt)[key],
  };
}
